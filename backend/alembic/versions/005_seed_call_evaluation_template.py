PROMPT = """ВАЖНЫЕ ИНСТРУКЦИИ ДЛЯ ОЦЕНКИ:

1. КЛАССИФИКАЦИЯ ЗВОНКА:
Определи тип звонка:
- brushoff_short: клиент сразу отшил, разговор < 2 минут, брокер не успел ничего сделать
- brushoff_with_attempt: клиент отшивает, но брокер ПЫТАЛСЯ перехватить инициативу или отработать возражения
- partial: разговор состоялся, но не все этапы пройдены (прервали, неудобно говорить)
- productive: полноценный разговор, основные этапы скрипта пройдены
- meeting_scheduled: встреча назначена

2. ЧЕК-ЛИСТ СКРИПТА:
Для каждого пункта чек-листа определи статус:
- completed: пункт выполнен
- attempted: брокер пытался, но клиент не дал (важно для brush-off!)
- not_applicable: пункт не применим к данному звонку
- not_reached: до этого пункта не дошли (НЕ штрафовать при brush-off)

3. ОЦЕНКА ПРИ BRUSH-OFF:
- При brushoff_short: оценивай только то, что брокер успел сделать. Если клиент сразу повесил трубку — ставь не ниже 3/10 за попытку.
- При brushoff_with_attempt: если брокер пытался перехватить инициативу и отработать возражение — это 6-7/10 даже если клиент отказал.
- Пункты со статусом not_reached НЕ должны снижать оценку.

4. ИНФОРМАЦИЯ ОТ КЛИЕНТА:
Извлекай ТОЛЬКО то, что сообщил КЛИЕНТ (не менеджер). Это ключевая ценность звонка.

5. ВОЗРАЖЕНИЯ:
Отдельно фиксируй каждое возражение клиента и как брокер его отработал. Это критически важно для обучения.

6. ОБЩИЕ ТРЕБОВАНИЯ:
Проверяй бинарные требования: имя клиента 3+ раз, приветствие, активное слушание, нет слов неуверенности, вежливость, позитивный настрой.

7. МНОГОЗВОНКОВОСТЬ:
Этот скрипт может растягиваться на несколько звонков. Если звонок явно является продолжением предыдущего разговора — отметь это. Не штрафуй за пропуск приветствия/представления если это follow-up звонок."""


