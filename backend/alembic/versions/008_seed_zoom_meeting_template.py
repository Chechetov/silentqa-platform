CRITERIA_TEXT = """Критерии оценки (каждый 0-10):
- preparation (Подготовка): по транскрипту видно, что связь/демонстрация проверены до клиента; фраза-маркер «связь проверена» или эквивалент
- greeting (Приветствие): по имени, тёплый контакт, упомянуто что встреча в Zoom
- connection_check (Проверка связи с клиентом): «слышно/видно?», «демонстрация видна?» — без этого встречу нельзя считать корректно начатой
- agenda (Старт встречи): согласована длительность, отвечено на стартовые вопросы клиента, проговорён маршрут встречи
- needs_recap (Резюмирование запроса): локация, бюджет, площадь, спальни, этаж, форма оплаты, ключевые критерии клиента — все позиции подтверждены
- presentation_quality (Качество презентации): карта/локация/план развития/окружение/панорама/транспорт; застройщик; архитектура и наполнение; инженерия; планировки со сценарием жизни — глубина и полнота
- purchase_terms (Условия покупки): ипотека, рассрочка, скидка за 100% — конкретные цифры, а не общие слова
- feedback_loop (Обратная связь после каждого ЖК): «что понравилось / насколько подходит / переходим?» после КАЖДОГО проекта, не только в конце
- objection_handling (Работа с возражениями): возражения зафиксированы и отработаны, а не проигнорированы
- closing (Подведение итогов и договорённости): впечатления клиента собраны; есть договор о визите в офис застройщика ИЛИ конкретная дата/время следующего контакта
- communication (Коммуникация): вежливость, активное слушание, ясность, имя клиента используется"""


