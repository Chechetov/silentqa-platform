MEETING_PLAYBOOK_CATEGORIES: list[str] = (
    [cat["id"] for cat in MEETING_PLAYBOOK["primary_approach"]]
    + [cat["id"] for cat in MEETING_PLAYBOOK["objection_responses"]]
)


def get_meeting_playbook_prompt(max_examples_per_category: int = 2) -> str:
    """Render MEETING_PLAYBOOK as markdown text for LLM system prompts.

    Compact: categories + 1-2 reference quotes per category + format guidance.
    LLM uses category IDs to tag recommendations for later follow-through matching.
    """
    lines: list[str] = [
        "## Библиотека аргументов закрытия на встречу",
        "",
        (
            "Ниже — категории аргументов с эталонными формулировками. Используй их как "
            "справочник: определяй подходящую категорию под ситуацию/возражение клиента "
            "и формулируй ответ в духе примеров (можно переформулировать под контекст). "
            "В своих ответах ссылайся на категорию по её `id` — это нужно для последующей "
            "оценки, какой аргумент сработал."
        ),
        "",
        "### Первый заход на встречу (после снятия запроса)",
        "",
    ]
    for cat in MEETING_PLAYBOOK["primary_approach"]:
        lines.append(f"**`{cat['id']}`** — {cat['title']}")
        lines.append(f"Когда: {cat['when_to_use']}")
        for quote in cat["examples"][:max_examples_per_category]:
            lines.append(f"• «{quote}»")
        lines.append("")

    lines.append("### Отработка отказа: «пришлите подборку» / «я подумаю» / «я сам посмотрю» / «нет времени»")
    lines.append("")
    for cat in MEETING_PLAYBOOK["objection_responses"]:
        triggers = ", ".join(f'«{t}»' for t in cat["triggers"])
        lines.append(f"**`{cat['id']}`** — {cat['title']}")
        lines.append(f"Триггеры клиента: {triggers}")
        for quote in cat["examples"][:max_examples_per_category]:
            lines.append(f"• «{quote}»")
        lines.append("")

    fmt = MEETING_PLAYBOOK["meeting_formats"]
    lines.append("### Формат встречи")
    lines.append("")
    lines.append(fmt["guidance"])
    lines.append("")
    lines.append("Варианты (в `meeting_formats_offered` quality-отчёта):")
    for fid, desc in fmt["options"].items():
        default_mark = " _(дефолт)_" if fid == fmt["default"] else ""
        lines.append(f"- `{fid}`{default_mark}: {desc}")
    lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def get_all_category_ids() -> list[str]:
    """Flat list of all meeting playbook category IDs (for schema validation)."""
    return list(MEETING_PLAYBOOK_CATEGORIES)
